export const DOMAINS = ['Healthcare', 'Smart City', 'Agriculture'];

/**
 * Filter results by domain and optionally return only Top 3 ranked teams.
 * Equal scores share the exact same rank position.
 */
export function getRound1Results({ domain = 'All', top3Only = false } = {}) {
  let list = ROUND_1_RESULTS;
  if (domain && domain !== 'All') {
    list = list.filter(item => item.domain.toLowerCase() === domain.toLowerCase());
  }
  if (top3Only) {
    list = list.filter(item => item.rank <= 3);
  }
  return list.sort((a, b) => {
    if (a.domain !== b.domain) return a.domain.localeCompare(b.domain);
    return a.rank - b.rank || b.average - a.average;
  });
}

/**
 * Group Top 3 teams by Domain
 */
export function getDomainTop3() {
  const result = {};
  DOMAINS.forEach(dom => {
    result[dom] = ROUND_1_RESULTS.filter(r => r.domain === dom && r.rank <= 3)
      .sort((a, b) => a.rank - b.rank || b.average - a.average);
  });
  return result;
}

/**
 * Summary telemetry stats
 */
export function getRound1Summary() {
  const total = ROUND_1_RESULTS.length;
  const top3Count = ROUND_1_RESULTS.filter(r => r.rank <= 3).length;
  return {
    totalEvaluated: total,
    totalTop3: top3Count,
    healthcareCount: ROUND_1_RESULTS.filter(r => r.domain === 'Healthcare').length,
    smartCityCount: ROUND_1_RESULTS.filter(r => r.domain === 'Smart City').length,
    agritechCount: ROUND_1_RESULTS.filter(r => r.domain === 'Agriculture').length,
  };
}
